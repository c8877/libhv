#!/usr/bin/env python3
"""把 frontend/{admin.html,admin.js,admin.css} 生成 embedded_frontend.cpp（编译期内嵌）。

用法：embed.py <frontend_dir> <output.cpp>
"""
import os
import sys

FILES = [("admin.html", "text/html"),
         ("admin.js", "application/javascript"),
         ("admin.css", "text/css")]


def main():
    srcdir, out = sys.argv[1], sys.argv[2]
    parts = []
    entries = []
    for i, (name, ctype) in enumerate(FILES):
        with open(os.path.join(srcdir, name), "rb") as f:
            data = f.read()
        arr = ",".join(str(b) for b in data)
        parts.append("static const unsigned char f%d[] = {%s};" % (i, arr))
        entries.append('    {"%s", "%s", f%d, sizeof(f%d)},' % (name, ctype, i, i))
    cpp = (
        "// generated by embed.py — do not edit\n"
        "struct EmbeddedFile {\n"
        "    const char* name;\n"
        "    const char* ctype;\n"
        "    const unsigned char* data;\n"
        "    unsigned int len;\n"
        "};\n\n"
        "extern const EmbeddedFile g_embedded_frontend[];\n"
        "extern const int g_embedded_frontend_count;\n\n"
        + "\n\n".join(parts)
        + "\n\nconst EmbeddedFile g_embedded_frontend[] = {\n"
        + "\n".join(entries)
        + "\n};\n"
        + "const int g_embedded_frontend_count = %d;\n" % len(FILES)
    )
    with open(out, "w") as f:
        f.write(cpp)


if __name__ == "__main__":
    main()
